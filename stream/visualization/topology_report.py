def design_payload(record: dict[str, Any], topology: HardwareTopology) -> dict[str, Any]:
    """One design as plain JSON: its metrics, and its topology with laid-out node positions.

    Positions are computed here, with the same `layout_positions` the PNGs use, so flipping between the page
    and a saved figure doesn't rearrange the cores."""
    positions = layout_positions(topology)
    cores = []
    for node in topology.nodes:
        x, y = positions.get(node.id, (0.0, 0.0))
        cores.append({**node.to_dict(), "x": float(x), "y": float(y)})
    return {
        "id": record["id"],
        "kind": record.get("kind", "unrolled"),
        "source_id": record.get("source_id"),
        "nb_cores": record.get("nb_cores"),
        "latency": record["latency"],
        "energy": record["energy"],
        "area": record["area"],
        "cores": cores,
        "edges": [edge.to_dict() for edge in topology.edges],
    }


def write_topology_report(
    designs: list[dict[str, Any]],
    html_path: str,
    *,
    json_path: str | None = None,
    title: str = "Stream schedule exploration",
    measured: list[dict[str, Any]] | None = None,
) -> None:
    """Write the interactive page (and, optionally, the same data as a standalone JSON for scripting)."""
    payload = {
        "schema": 1,
        # `Core.get_area()` mixes the operational array's unit area with CACTI mm^2, so it carries no single
        # physical unit -- the same caveat the trade-off figure's axis label makes.
        "objectives": {"latency": "cycles", "energy": "pJ", "area": "a.u."},
        "designs": designs,
        "measured": [
            {
                "id": record["id"],
                "kind": record.get("kind", "unrolled"),
                "latency": record["latency"],
                "energy": record["energy"],
                "area": record["area"],
            }
            for record in (measured or [])
        ],
    }
    encoded = json.dumps(payload).replace("</", "<\\/")
    # Plain replacement, never `str.format`/f-string: the template is full of CSS and JS braces.
    html = _TEMPLATE.replace("__TOPOLOGY_DATA__", encoded).replace("__TITLE__", title)
    os.makedirs(os.path.dirname(html_path) or ".", exist_ok=True)
    with open(html_path, "w", encoding="utf-8") as handle:
        handle.write(html)
    if json_path:
        with open(json_path, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, indent=1)
    logger.info(f"Saved interactive topology report for {len(designs)} design(s) to {html_path}.")
