"""One self-contained page for browsing an exploration's Pareto front and the hardware each point implies.

The PNGs in `hardware_graph` answer "what does design N look like"; this answers "which design should I care
about, and what does *that* one look like" -- you pick a point off the trade-off scatter and its topology is
drawn beside it. For a rolled search the comparison is the whole point, so two designs can be pinned side by
side with the edges that the fold added or removed highlighted.

Deliberately dependency-free. The data is inlined into the page rather than fetched from the sibling JSON,
because these artifacts get opened straight off disk (`file://`, over SSH, out of a cluster output directory)
where a `fetch()` of a neighbouring file is blocked by CORS. The scatter and the graph are hand-built SVG: no
charting library to pin, no build step, and the node positions come from `layout_positions`, so the page and
the PNGs place the same cores in the same spots.
"""

