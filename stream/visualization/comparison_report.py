def write_comparison_report(data: dict[str, Any], html_path: str, *, title: str = "Optimizer comparison") -> None:
    """Write the page. `data` is `{"workloads": [...], "by_workload": {w: {...}}, "budget": {...}}` as built by
    `analyze_optimizer_comparison.build_report_data`; method styles are added here."""
    payload = {**data, "styles": METHOD_STYLES, "default_style": DEFAULT_STYLE}
    encoded = json.dumps(payload, allow_nan=False).replace("</", "<\\/")
    # Plain replacement, never `str.format`/f-string: the template is full of CSS and JS braces.
    html = _TEMPLATE.replace("__DATA__", encoded).replace("__TITLE__", title)
    os.makedirs(os.path.dirname(html_path) or ".", exist_ok=True)
    with open(html_path, "w", encoding="utf-8") as handle:
        handle.write(html)
    logger.info(f"Saved the interactive comparison report to {html_path}.")
